def test_failure_between_temp_write_and_replace_keeps_old_lock(tmp_path, monkeypatch):
    out = tmp_path / "overlay.lock.json"
    out.write_bytes(b"previous lock\n")

    def boom(src, dst):
        assert Path(src).read_bytes().startswith(b"{")  # the temp file was fully written
        raise OSError("simulated crash before rename")

    monkeypatch.setattr(rp.os, "replace", boom)
    with pytest.raises(OSError, match="simulated"):
        run(Stub(), out)
    assert out.read_bytes() == b"previous lock\n"
    assert [p.name for p in tmp_path.iterdir()] == ["overlay.lock.json"]


def test_failure_while_writing_temp_keeps_old_lock(tmp_path, monkeypatch):
    out = tmp_path / "overlay.lock.json"
    out.write_bytes(b"previous lock\n")
    monkeypatch.setattr(rp.os, "fsync", lambda fd: (_ for _ in ()).throw(OSError("disk full")))
    with pytest.raises(OSError, match="disk full"):
        rp.write_atomically(out, b"new")
    assert out.read_bytes() == b"previous lock\n"
    assert [p.name for p in tmp_path.iterdir()] == ["overlay.lock.json"]


