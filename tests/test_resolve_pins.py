@pytest.mark.parametrize("case", sorted(FAILURES))
def test_failure_names_field_and_leaves_lock_unchanged(case, tmp_path, capsys):
    field, breaker = FAILURES[case]
    out = tmp_path / "overlay.lock.json"
    out.write_bytes(b"previous lock\n")
    before = os.stat(out)
    stub = Stub()
    breaker(stub)
    assert run(stub, out) != 0
    err = capsys.readouterr().err
    assert f"error: {field}: " in err, err
    assert "left unchanged" in err
    assert out.read_bytes() == b"previous lock\n"
    assert os.stat(out).st_ino == before.st_ino
    assert sorted(p.name for p in tmp_path.iterdir()) == ["overlay.lock.json"]


