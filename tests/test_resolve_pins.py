class Stub:
    """An Upstream whose replies are plain dicts, so each test can break one lookup."""

    def __init__(self):
        self.gets: dict[str, object] = {
            PB_URL: [
                {"name": n, "product_version": V,
                 "transfer_manifest_url": f"gs://fuchsia-public-artifacts-release/builds/{b}/product_bundles/{n}/transfer.json"}
                for b, n in zip(BUILDS, ["core.vim3", "core.x64", "minimal.arm64"])
            ],
            **{sm_url(b): source_manifest() for b in BUILDS},
            IDK_META_URL: {"size": str(len(IDK_BYTES)),
                           "md5Hash": base64.b64encode(hashlib.md5(IDK_BYTES).digest()).decode()},
        }
        # (package, version) -> instance hex digest, or an int HTTP status to fail with.
        self.cipd: dict[tuple[str, str], object] = {
            ("fuchsia/sdk/core/linux-amd64", f"version:{V}"): IDK_CIPD_ID,
            ("fuchsia/third_party/rust/host/linux-amd64", RUST_PIN): HOST_ID,
            ("fuchsia/third_party/rust/target/fuchsia", RUST_PIN): TARGET_ID,
            ("fuchsia/development/rules_fuchsia", f"git_revision:{INTEG}"): RULES_ID,
            ("fuchsia/development/rules_fuchsia", f"version:{V}"): RULES_ID,
        }
        self.tags: dict[tuple[str, str], list[dict]] = {
            ("fuchsia/sdk/core/linux-amd64", IDK_CIPD_ID): [
                {"key": "git_revision", "value": INTEG}, {"key": "version", "value": V}],
        }
        self.digests: dict[str, object] = {IDK_URL: IDK_BYTES}
        self.git: dict[str, object] = {"manifests/toolchain": TOOLCHAIN_XML,
                                       "third_party/rust_crates/Cargo.lock": CARGO_LOCK}
        self.git_error: str | None = None
        self.calls: list[tuple] = []

    def get(self, url):
        self.calls.append(("get", url))
        reply = self.gets.get(url, 404)
        if isinstance(reply, int):
            raise rp.FetchError(f"GET {url}: HTTP {reply}", reply)
        return reply if isinstance(reply, bytes) else json.dumps(reply).encode()

    def post_json(self, url, payload):
        self.calls.append(("post", url, json.dumps(payload, sort_keys=True)))
        assert url.startswith("https://chrome-infra-packages.appspot.com/prpc/cipd.Repository/")
        method, package = url.rsplit("/", 1)[1], payload["package"]
        if method == "ResolveVersion":
            reply = self.cipd.get((package, payload["version"]), 404)
            if isinstance(reply, int):
                raise rp.FetchError(f"HTTP {reply} no such tag", reply)
            if isinstance(reply, bytes):  # a raw, possibly malformed, reply body
                return b")]}'\n" + reply
            body = {"package": package, "instance": {"hashAlgo": "SHA256", "hexDigest": reply}}
        elif method == "DescribeInstance":
            assert payload["describeTags"] is True
            tags = self.tags.get((package, payload["instance"]["hexDigest"]), [])
            if isinstance(tags, bytes):
                return b")]}'\n" + tags
            body = {"instance": payload["instance"], "tags": tags}
        else:
            raise AssertionError(method)
        return b")]}'\n" + json.dumps(body).encode()

    def digest(self, url):
        self.calls.append(("digest", url))
        data = self.digests.get(url, 404)
        if isinstance(data, Exception):
            raise data
        if isinstance(data, int):
            raise rp.FetchError(f"GET {url}: HTTP {data}", data)
        return rp.Digest(hashlib.sha256(data).hexdigest(), hashlib.md5(data).hexdigest(), len(data))

    def git_show(self, repo, revision, path):
        # Like LiveUpstream: a fetch failure or a missing path raises FetchError.
        self.calls.append(("git", repo, revision, path))
        assert repo == "https://fuchsia.googlesource.com/fuchsia"
        if self.git_error:
            raise rp.FetchError(self.git_error)
        if path not in self.git:
            raise rp.FetchError(f"git cat-file -p {revision}:{path}: fatal: path '{path}' does not exist")
        return self.git[path]


def run(stub: Stub, out: Path, version: str = V) -> int:
    return rp.main([version, "--out", str(out)], upstream=stub)


