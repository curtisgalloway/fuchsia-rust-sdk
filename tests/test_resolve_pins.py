def test_live_git_ignores_user_and_env_git_config(local_repo, tmp_path, monkeypatch):
    """C1: config from HOME, XDG, GIT_CONFIG_* and ~/.netrc must not reach the fetch.

    The hostile config rewrites the repository URL to a path that does not exist, sets a
    cookie file and an extra header, and a ~/.netrc holds a password. The control run
    shows plain git obeys it; the resolver's git must not.
    """
    url, first = local_repo
    home = tmp_path / "hostile-home"
