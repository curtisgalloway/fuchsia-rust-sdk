def test_happy_path_writes_every_field_with_a_source(tmp_path):
    out = tmp_path / "overlay.lock.json"
    assert run(Stub(), out) == 0
    lock = json.loads(out.read_text())
    assert sorted(lock) == ["bazel_sdk", "cargo_lock_sha256", "fuchsia_revision", "integration_revision",
                            "rules_fuchsia", "rust_host", "rust_target", "sdk_version"]
    for field, entry in lock.items():
        assert entry["value"], field
        assert entry["source"] and all(isinstance(s, str) and s for s in entry["source"]), field
    assert lock["sdk_version"] == {"value": V, "source": [PB_URL]}
    assert lock["fuchsia_revision"] == {"value": FX, "source": sorted(sm_url(b) for b in BUILDS)}
    assert lock["integration_revision"]["value"] == INTEG
    assert lock["integration_revision"]["source"][-1] == (
        f"https://chrome-infra-packages.appspot.com/p/fuchsia/sdk/core/linux-amd64/+/version:{V}")
    assert lock["rust_host"] == {
        "package": "fuchsia/third_party/rust/host/linux-amd64",
        "value": HOST_ID,
        "source": [f"https://fuchsia.googlesource.com/fuchsia {FX}:manifests/toolchain",
                   f"https://chrome-infra-packages.appspot.com/p/fuchsia/third_party/rust/host/linux-amd64/+/{RUST_PIN}"],
    }
    assert lock["rust_target"]["package"] == "fuchsia/third_party/rust/target/fuchsia"
    assert lock["rust_target"]["value"] == TARGET_ID
    assert lock["bazel_sdk"] == {"url": IDK_URL, "value": hashlib.sha256(IDK_BYTES).hexdigest(), "source": [IDK_URL]}
    assert lock["rules_fuchsia"] == {
        "package": "fuchsia/development/rules_fuchsia",
        "value": RULES_ID,
        "source": [f"https://chrome-infra-packages.appspot.com/p/fuchsia/development/rules_fuchsia/+/git_revision:{INTEG}"],
    }
    assert lock["cargo_lock_sha256"] == {
        "value": hashlib.sha256(CARGO_LOCK).hexdigest(),
        "source": [f"https://fuchsia.googlesource.com/fuchsia {FX}:third_party/rust_crates/Cargo.lock"],
    }


