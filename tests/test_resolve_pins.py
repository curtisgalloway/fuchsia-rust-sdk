def make_elf(build_ids=(FIDLGEN_ID,), machine: int = 62, elf_class: int = 2, note_type: int = 3,
             note_name: bytes = b"GNU\0", truncate_note: bool = False) -> bytes:
    """A minimal little-endian ELF: a header, one SHT_NOTE section per build ID, and the
    section header table (a null section first, as linkers write it)."""
    notes = []
    for bid in build_ids:
        desc = bytes.fromhex(bid)
        notes.append(struct.pack("<III", len(note_name), len(desc), note_type) + note_name
                     + b"\0" * (-len(note_name) % 4) + desc + b"\0" * (-len(desc) % 4))
    body_off = 64
    body = b"".join(notes)
    shoff = body_off + len(body)
    sections = [bytes(64)]
    off = body_off
    for n in notes:
        size = len(n) + (10000 if truncate_note else 0)
        sections.append(struct.pack("<IIQQQQIIQQ", 1, 7, 2, 0, off, size, 0, 0, 4, 0))
        off += len(n)
    header = (b"\x7fELF" + bytes([elf_class, 1, 1, 0]) + bytes(8)
              + struct.pack("<HHIQQQIHHHHHH", 3, machine, 1, 0, 0, shoff, 0, 64, 56, 0, 64, len(sections), 0))
    assert len(header) == 64
    return header + body + b"".join(sections)


