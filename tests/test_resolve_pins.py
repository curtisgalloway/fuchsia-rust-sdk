def test_live_git_ignores_user_and_env_git_config(local_repo, tmp_path, monkeypatch):
    """C1: config from HOME, XDG, GIT_CONFIG_* and ~/.netrc must not reach the fetch.

    The hostile config rewrites the repository URL to a path that does not exist, sets a
    cookie file and an extra header, and a ~/.netrc holds a password. The control run
    shows plain git obeys it; the resolver's git must not.
    """
    url, first = local_repo
    home = tmp_path / "hostile-home"
    (home / "git").mkdir(parents=True)
    bogus = (tmp_path / "does-not-exist").as_uri()
    hostile = (f'[url "{bogus}"]\n\tinsteadOf = {url}\n'
               f"[http]\n\tcookiefile = {home}/cookies\n\textraHeader = Authorization: Bearer leaked\n")
    (home / ".gitconfig").write_text(hostile)
    (home / "git" / "config").write_text(hostile)
    (home / "cookies").write_text(".googlesource.com\tTRUE\t/\tTRUE\t2147483647\to\tgit-x=leaked\n")
    (home / ".netrc").write_text("machine fuchsia.googlesource.com login x password leaked\n")
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("XDG_CONFIG_HOME", str(home))
    monkeypatch.delenv("GIT_CONFIG_GLOBAL", raising=False)
    monkeypatch.delenv("GIT_CONFIG_NOSYSTEM", raising=False)
    monkeypatch.setenv("GIT_CONFIG_COUNT", "1")
    monkeypatch.setenv("GIT_CONFIG_KEY_0", f"url.{bogus}.insteadOf")
    monkeypatch.setenv("GIT_CONFIG_VALUE_0", url)
    monkeypatch.setenv("GIT_CONFIG_PARAMETERS", f"'url.{bogus}.insteadof'='{url}'")

    # Control: plain git under this environment is redirected and fails.
    probe = tmp_path / "probe.git"
    subprocess.run(["git", "init", "-q", "--bare", str(probe)], check=True, capture_output=True)
    control = subprocess.run(["git", "-C", str(probe), "fetch", "-q", "--depth", "1", url, first],
                             capture_output=True)
    assert control.returncode != 0 and b"does-not-exist" in control.stderr

    up = rp.LiveUpstream()
    try:
        assert up.git_show(url, first, "manifests/toolchain") == b"old\n"
    finally:
        up.close()


def _serve_once(handler_body):
    """Serve one HTTP response on 127.0.0.1 from a thread; returns the URL."""
    import http.server
    import threading

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802
            handler_body(self)

        def log_message(self, *args):
            pass

    server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.handle_request, daemon=True).start()
    return f"http://127.0.0.1:{server.server_port}/core.tar.gz"


def _truncated(h):
    h.send_response(200)
    h.send_header("Content-Length", "1000")
    h.end_headers()
    h.wfile.write(b"only a little")
    h.wfile.flush()
    h.close_connection = True


