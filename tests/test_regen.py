def test_vendor_from_git_matches_vendor_from_directory(git_upstream, tmp_path):
    src, rev = git_upstream
    repo_git = make_repo(tmp_path / "r1", src)
    repo_dir = make_repo(tmp_path / "r2", src)
    for repo in (repo_git, repo_dir):
        lock = json.loads((repo / "overlay.lock.json").read_text())
        lock["fuchsia_revision"]["value"] = rev
        (repo / "overlay.lock.json").write_text(json.dumps(lock))
    assert regen.main(["vendor"], root=repo_git,
                      make_source=lambda r: regen.GitSource(src.as_uri(), r, tmp_path / "w")) == 0
    assert regen.main(["vendor"], root=repo_dir, make_source=lambda r: regen.DirSource(src, r)) == 0
