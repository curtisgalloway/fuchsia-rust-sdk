def test_check_names_a_one_byte_hand_edit(env, capsys):
    _, repo, run = env
    assert run("vendor") == 0
    f = repo / "vendor/fuchsia/sdk/rust/a/src/lib.rs"
    data = bytearray(f.read_bytes())
