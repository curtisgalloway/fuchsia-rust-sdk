def _snapshot(root: Path) -> dict[str, tuple[bytes, int]]:
    out = {}
    for rel in regen.OUTPUTS:
        for p in sorted((root / rel).rglob("*")):
            if p.is_file():
                out[p.relative_to(root).as_posix()] = (p.read_bytes(), p.stat().st_mode & 0o777)
    return out


