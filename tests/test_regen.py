def test_vendor_writes_the_expected_trees(env):
    upstream, repo, run = env
    assert run("vendor") == 0
    v = repo / "vendor/fuchsia"
    assert sorted(p.relative_to(v).as_posix() for p in v.rglob("*") if p.is_file()) == [
        "BUILD.bazel", "LICENSE", "PATENTS",
        "sdk/rust/a/BUILD.bazel", "sdk/rust/a/BUILD.gn", "sdk/rust/a/src/lib.rs", "sdk/rust/a/tool.sh",
        "sdk/rust/b/BUILD.bazel", "sdk/rust/b/BUILD.gn", "sdk/rust/b/src/lib.rs",
    ]
    # Copied byte for byte, modes kept; LICENSE covers the tree (C4).
    for rel in ("LICENSE", "PATENTS", "sdk/rust/a/src/lib.rs", "sdk/rust/b/src/lib.rs"):
        assert (v / rel).read_bytes() == (upstream / rel).read_bytes()
    assert (v / "sdk/rust/a/tool.sh").stat().st_mode & 0o111
    assert not (v / "sdk/rust/a/src/lib.rs").stat().st_mode & 0o111
    a = (v / "sdk/rust/a/BUILD.bazel").read_text()
    assert a.startswith(f"# Generated by scripts/regen.py from fuchsia.git {REV}:sdk/rust/a/BUILD.bazel\n")
    assert A_BUILD.splitlines()[0] in a  # upstream's own header is kept
    assert (v / "sdk/rust/b/BUILD.bazel").read_text() == B_OVERLAY
    assert 'license_text = "LICENSE"' in (v / "BUILD.bazel").read_text()

    c = repo / "third_party/crates"
    spec = json.loads((c / "crates.json").read_text())
    assert spec["aliases"] == ["foo"]  # baz is not used, so not fetched
    assert [(e["name"], e["version"], e["sha256"][:4], e["url"]) for e in spec["crates"]] == [
        ("bar", "0.2.0-rc.1", "2222", "https://static.crates.io/crates/bar/bar-0.2.0-rc.1.crate"),
        ("foo", "1.0.0", "1111", "https://static.crates.io/crates/foo/foo-1.0.0.crate"),
    ]
    assert spec["cargo_lock"].endswith(f"{REV}:third_party/rust_crates/Cargo.lock")
    assert '"//vendor/bar-0.2.0-rc.1:bar"' in (c / "BUILD.foo-1.0.0.bazel").read_text()
    aliases = (c / "BUILD.vendor.bazel").read_text()
    assert 'name = "foo",\n    actual = "//vendor/foo-1.0.0:foo"' in aliases and '"baz"' not in aliases
    assert sorted(p.name for p in c.iterdir()) == [
        "BUILD.bar-0.2.0-rc.1.bazel", "BUILD.bazel", "BUILD.foo-1.0.0.bazel", "BUILD.vendor.bazel", "crates.json"]


