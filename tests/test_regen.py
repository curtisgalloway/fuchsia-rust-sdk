def test_rewrite_maps_every_label_kind():
    out = regen.rewrite_upstream_build(A_BUILD, "sdk/rust/a/BUILD.bazel", {"sdk/rust/a", "sdk/rust/b"})
    assert 'load("//rules:rustc.bzl", "rustc_library")' in out
    assert '"//vendor/fuchsia:license"' in out
    assert '"//rules/lints:clippy_warn_all"' in out
    assert '"//vendor/fuchsia/sdk/rust/b"' in out
    assert '"@rust_crates//vendor:foo"' in out
    assert '"//visibility:public"' in out and '"//conditions:default"' in out
    assert '# A comment naming "//build/not/a/label" is left alone.' in out
    assert "rustc_library(\n    vendored = True,  # Generated by scripts/regen.py\n    name = \"a\"," in out
    # Nothing else changed: undoing the known edits gives the original back.
    undo = (out.replace("//rules:rustc.bzl", "//build/bazel/rules/rust:defs.bzl")
            .replace("//vendor/fuchsia:license", "//:license")
            .replace("//rules/lints:", "//build/config/rust/lints:")
            .replace("//vendor/fuchsia/sdk/rust/b", "//sdk/rust/b")
            .replace("@rust_crates//vendor:", "//third_party/rust_crates/vendor:")
            .replace("\n    vendored = True,  # Generated by scripts/regen.py", ""))
    assert undo == A_BUILD


