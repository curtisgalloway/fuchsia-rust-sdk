def _patch(old: str, new: str, path="sdk/rust/a/src/lib.rs") -> str:
    return (f"--- a/{path}\n+++ b/{path}\n@@ -1,3 +1,3 @@\n pub fn a() -> u32 {{\n"
            f"-    {old}\n+    {new}\n }}\n")


