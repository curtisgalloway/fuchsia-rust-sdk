def _crate_build(name, version, deps=()):
    dep_lines = "".join(f'        "{d}",\n' for d in deps)
    return f'''\
# @generated by crate_universe
load("@rules_rust//rust:defs.bzl", "rust_library")

package(default_visibility = ["//visibility:public"])

package_info(
    name = "package_info",
    package_name = "{name}",
    package_url = "https://example.invalid/{name}",
    package_version = "{version}",
)

rust_library(
    name = "{name}",
    srcs = glob(["**/*.rs"]),
    target_compatible_with = select({{
        "@rules_rust//rust/platform:x86_64-unknown-fuchsia": [],
        "//conditions:default": ["@platforms//:incompatible"],
    }}),
    deps = [
{dep_lines}    ],
)
'''


def _write(root: Path, rel: str, data, mode=0o644):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data if isinstance(data, bytes) else data.encode())
    p.chmod(mode)


def make_upstream(root: Path) -> Path:
    _write(root, "LICENSE", "Fuchsia license text\n")
    _write(root, "PATENTS", "Fuchsia patents text\n")
    _write(root, "sdk/rust/a/BUILD.bazel", A_BUILD)
    _write(root, "sdk/rust/a/BUILD.gn", "# gn\n")
    _write(root, "sdk/rust/a/src/lib.rs", "pub fn a() -> u32 {\n    1\n}\n")
    _write(root, "sdk/rust/a/tool.sh", "#!/bin/sh\n", 0o755)
    # A package of its own inside the crate directory: not copied with it.
    _write(root, "sdk/rust/a/nested/BUILD.gn", "# gn\n")
    _write(root, "sdk/rust/a/nested/src/lib.rs", "// nested\n")
    _write(root, "sdk/rust/b/BUILD.gn", "# gn only\n")
    _write(root, "sdk/rust/b/src/lib.rs", "pub fn b() {}\n")
    _write(root, "third_party/rust_crates/Cargo.lock", CARGO_LOCK)
    _write(root, "third_party/rust_crates/vendor/BUILD.bazel", ALIASES)
    _write(root, "third_party/rust_crates/vendor/foo-1.0.0/BUILD.bazel", _crate_build(
        "foo", "1.0.0", ["//third_party/rust_crates/vendor/bar-0.2.0-rc.1:bar"]))
    _write(root, "third_party/rust_crates/vendor/bar-0.2.0-rc.1/BUILD.bazel", _crate_build("bar", "0.2.0-rc.1"))
    _write(root, "third_party/rust_crates/vendor/baz-0.1.0/BUILD.bazel", _crate_build("baz", "0.1.0"))
    return root


def make_repo(root: Path, upstream: Path) -> Path:
    lock_sha = hashlib.sha256((upstream / "third_party/rust_crates/Cargo.lock").read_bytes()).hexdigest()
    lock = {"fuchsia_revision": {"value": REV, "source": []},
            "cargo_lock_sha256": {"value": lock_sha, "source": []}}
    _write(root, "overlay.lock.json", json.dumps(lock))
    _write(root, "vendor/crates.txt", "# comment\nsdk/rust/a upstream\nsdk/rust/b overlay  # ours\n")
    _write(root, "overlays/sdk/rust/b/BUILD.bazel", B_OVERLAY)
    return root


